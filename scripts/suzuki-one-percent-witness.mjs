const gcd=(a,b)=>{a=a<0n?-a:a;b=b<0n?-b:b;while(b)[a,b]=[b,a%b];return a;};
class Q {
  constructor(n,d=1n){n=BigInt(n);d=BigInt(d);if(d<0n){n=-n;d=-d;}const g=gcd(n,d);this.n=n/g;this.d=d/g;}
  add(b){return new Q(this.n*b.d+b.n*this.d,this.d*b.d);}
  sub(b){return this.add(new Q(-b.n,b.d));}
  mul(b){return new Q(this.n*b.n,this.d*b.d);}
  div(b){return new Q(this.n*b.d,this.d*b.n);}
  pow(k){return new Q(this.n**BigInt(k),this.d**BigInt(k));}
  floor(){return this.n>=0n?this.n/this.d:-((-this.n+this.d-1n)/this.d);}
  ceil(){return -new Q(-this.n,this.d).floor();}
  num(){return Number(this.n)/Number(this.d);}
}
